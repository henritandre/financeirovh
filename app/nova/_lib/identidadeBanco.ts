/** Identidade visual local. Prioriza o banco vinculado; apelidos são fallback. */
export function identidadeBanco(nome: string) {
  const texto = nome.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
  const identidades = [
    { chave: "itau", sigla: "i", padrao: /\bitau\b/ },
    { chave: "nubank", sigla: "nu", padrao: /\b(nubank|nu)\b/ },
    { chave: "inter", sigla: "in", padrao: /\binter\b/ },
    { chave: "caixa", sigla: "cx", padrao: /\bcaixa\b/ },
    { chave: "santander", sigla: "s", padrao: /\bsantander\b/ },
    { chave: "mercantil", sigla: "m", padrao: /\bmercantil\b/ },
    { chave: "bradesco", sigla: "b", padrao: /\bbradesco\b/ },
    { chave: "bb", sigla: "bb", padrao: /\b(banco do brasil|bb)\b/ },
    { chave: "c6", sigla: "c6", padrao: /\bc6\b/ },
    { chave: "btg", sigla: "btg", padrao: /\bbtg\b/ },
    { chave: "picpay", sigla: "pp", padrao: /\bpic ?pay\b/ },
    { chave: "mercadopago", sigla: "mp", padrao: /\bmercado ?pago\b/ },
    { chave: "pagbank", sigla: "pb", padrao: /\b(pagbank|pagseguro)\b/ },
    { chave: "neon", sigla: "ne", padrao: /\bneon\b/ },
    { chave: "xp", sigla: "xp", padrao: /\bxp\b/ },
    { chave: "stone", sigla: "st", padrao: /\bstone\b/ },
    { chave: "cora", sigla: "co", padrao: /\bcora\b/ },
    { chave: "safra", sigla: "sf", padrao: /\bsafra\b/ },
    { chave: "bmg", sigla: "bmg", padrao: /\bbmg\b/ },
    { chave: "pan", sigla: "pan", padrao: /\b(banco pan|pan)\b/ },
    { chave: "original", sigla: "or", padrao: /\boriginal\b/ },
    { chave: "banrisul", sigla: "br", padrao: /\bbanrisul\b/ },
    { chave: "brb", sigla: "brb", padrao: /\bbrb\b/ },
    { chave: "bnb", sigla: "bnb", padrao: /\b(bnb|banco do nordeste)\b/ },
    { chave: "sicoob", sigla: "sc", padrao: /\bsicoob\b/ },
    { chave: "sicredi", sigla: "si", padrao: /\bsicredi\b/ },
    { chave: "unicred", sigla: "un", padrao: /\bunicred\b/ },
    { chave: "carteira", sigla: "$", padrao: /\b(carteira|casa|dinheiro)\b/ },
  ];
  return identidades.find(item => item.padrao.test(texto)) ?? { chave: "neutro", sigla: nome.trim().charAt(0).toUpperCase() || "◇" };
}

